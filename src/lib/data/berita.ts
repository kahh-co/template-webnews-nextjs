export function getAllBerita(): Berita[] {
  return [...beritaList].sort((a, b) => new Date(b.tanggalTerbit).getTime() - new Date(a.tanggalTerbit).getTime());
}

export function getBeritaBySlug(slug: string): Berita | undefined {
  return beritaList.find((b) => b.slug.toLowerCase() === slug.toLowerCase());
}

export function getBeritaByKategori(kategoriSlug: string): Berita[] {
  return getAllBerita().filter((b) => b.kategori.toLowerCase() === kategoriSlug.toLowerCase());
}

export function getHeadlineBerita(): Berita {
  return beritaList.find((b) => b.headline) || beritaList[0];
}

export function getBeritaPopuler(limit: number = 5): Berita[] {
  return getAllBerita().filter((b) => b.populer).slice(0, limit);
}

export function getBeritaTrending(limit: number = 6): Berita[] {
  return getAllBerita().filter((b) => b.trending || b.populer).slice(0, limit);
}

export function getBeritaTerkait(currentSlug: string, kategoriSlug: string, limit: number = 3): Berita[] {
  return getAllBerita()
    .filter((b) => b.slug !== currentSlug && b.kategori.toLowerCase() === kategoriSlug.toLowerCase())
    .slice(0, limit);
}

export function cariBerita(query: string, kategoriSlug?: string): Berita[] {
  const q = query.toLowerCase().trim();
  if (!q && !kategoriSlug) return getAllBerita();

  return getAllBerita().filter((b) => {
    const matchesQuery =
      !q ||
      b.judul.toLowerCase().includes(q) ||
      b.excerpt.toLowerCase().includes(q) ||
      b.tags.some((t) => t.toLowerCase().includes(q)) ||
      b.penulis.nama.toLowerCase().includes(q);

    const matchesKategori = !kategoriSlug || b.kategori.toLowerCase() === kategoriSlug.toLowerCase();

    return matchesQuery && matchesKategori;
  });
}
